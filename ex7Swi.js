//pedindio para usuario 
let dia = Number(prompt("Digita um numero de 1 a 5 para o dia da semana"))

//Verificandoi com switch qual foi o dia escolhido 
switch(dia){
    case 1:
        // se o numero for 1 
    alert("Segunda-feira: Sias um dia lindo. Bom dia!!!!!!!!!!!!")
    break

    case 2: 
    alert("Terça-feira: Quase quarta!!!!!!!")
    break

    case 3: 
    alert("Quarta-feira: So falta dois dias!")
    break

    case 4: 
    alert("Quinta-feira: Seria um dia tambem para festejar!")
    break

    case 5: 
    alert("Sexta=feira: Mas ja chegou o dia!")
    break
    
    default:
    alert("feriado!!!!!!")

}
    
